// Package sourceauthority qualifies an exact Git source at a build or signing
// boundary. It has private bounded response transport, but no configured provider
// installation, credential access, build or signing effect.
// Its configured Source and Clock are trusted adapter dependencies, never request
// inputs. Fixture Sources establish no actual hosting-provider authority.
package sourceauthority

import (
	"context"
	"errors"
	"time"
)

const (
	AuthorityBudget = 30 * time.Second
	MaxScopes       = 4
	MaxPages        = 256
	MaxEvents       = 16384
	MaxBodyBytes    = 16 << 20
)

// Profile bounds raw local adapter material whose capacity is not fixed by the
// wire contract. These installed limits need source-owner qualification; they
// are not caller options or an additional release policy.
type Profile struct {
	CommitBytes, AncestryCommits, PlatformReviews, CheckRecords int
}

// OwnerKey is admitted by installed policy for one canonical repository. SSH
// Ed25519 is the implemented cryptographic subset; no real owner key is selected
// or admitted by this package. PublicKey is the binary SSH public-key encoding.
type OwnerKey struct {
	Repository, Fingerprint string
	PublicKey               []byte
}

// Policy must originate in protected installed configuration. It is defensively
// copied by New. Matrix sender IDs are exact authenticated member identifiers;
// display names, relays and publishing hosting accounts establish no identity.
type Policy struct {
	Product, Alias, CanonicalRepository, RepositoryName, DefaultBranch string
	SHA256, MatrixOrigin, ProducerSender                               string
	ReviewerSenders, Scopes                                            []string
	OwnerKeys                                                          []OwnerKey
	Profile                                                            Profile
}

type Phase string

const (
	Prebuild Phase = "prebuild"
	Presign  Phase = "presign"
)

// Request contains correlation and configured source selection, never evidence
// or an authority assertion. Nonce must be freshly service-generated at each
// boundary by the eventual composition layer.
type Request struct {
	OperationID, Nonce, Product, Repository, Commit, PolicySHA256 string
}

// Query is generated by the verifier and echoed in a trusted Source response.
type Query struct {
	Request
	Phase Phase
}

// Reading is supplied by a trusted same-process clock/discontinuity detector.
// Epoch changes on restart or detected wall-clock discontinuity. An error means
// unknown time. Monotonic must never decrease within an epoch. Host qualification
// of that detector is deliberately not claimed by this pure component.
type Reading struct {
	Wall      time.Time
	Monotonic time.Duration
	Epoch     string
	// SampleSpan bounds elapsed time from the leading Monotonic endpoint to
	// completion of this reading. Wall was sampled inside that interval, so
	// Wall+SampleSpan is a conservative upper wall bound at completion.
	// Zero denotes a point reading; sampled adapters must report the full span.
	SampleSpan time.Duration
}

// end is used only after validReading has checked the addition for overflow.
func (r Reading) end() time.Duration { return r.Monotonic + r.SampleSpan }
func (r Reading) wallEnd() time.Time { return r.Wall.Add(r.SampleSpan) }

type Clock interface {
	Read() (Reading, error)
}

// Source is the privileged authenticated acquisition/normalization boundary.
// Read must use ONLY configured canonical authorities, read current policy,
// default branch, PR/review state and checks, and authenticate Matrix origin,
// sender, producer handoff, pages and per-scope frontiers. It must obey ctx and
// bound allocations before returning material. It cannot be selected or fed by
// a release caller. No boolean verification callback or caller evidence API
// exists. Implementing this interface is a trust grant, not proof of correctness.
// This unit supplies no production implementation of that trust grant.
type Source interface {
	Read(context.Context, Query) (Observation, error)
}

// Coverage distinguishes a successfully complete read from unknown or partial
// provider responses (including permissions errors). A green result is not
// coverage and cannot establish a check policy.
type Coverage string

const (
	Complete Coverage = "complete"
	Partial  Coverage = "partial"
	Unknown  Coverage = "unknown"
)

type PolicyState string

const (
	Current PolicyState = "current"
	Revoked PolicyState = "revoked"
)

// Observation is adapter-private data, not the wire projection and not a client
// envelope. Its status fields describe authenticated provider reads; none is a
// substitute for the predicates independently checked below. Source retains
// custody while Read returns, then transfers stable ownership to the verifier.
type Observation struct {
	Binding               Query
	ObservedAt, ExpiresAt int64
	PolicySHA256          string
	PolicyState           PolicyState
	Repository            RepositoryRecord
	Commit                []byte
	// Path starts at the observed default head and ends immediately before
	// the requested commit; each next raw Git commit must be a real parent.
	// Equal landing has an empty path. No rewriting or tree-only match passes.
	LandingPath [][]byte
	PR          PullRequest
	Producer    ProducerHandoff
	Reviews     ReviewInventory
	Checks      CheckInventory
	CheckPolicy CheckPolicy
	Lookup      Lookup
}

type RepositoryRecord struct {
	Canonical, DefaultBranch, DefaultHead string
}

type PullRequest struct {
	Repository, Head, Base, State string // State must be merged, never draft/open.
	Number                        uint64
}

// ProducerHandoff is normalized only from the configured origin's authenticated
// exact-head handoff, not a claimed JSON sender. Its actual parser/custody is an
// explicit production dependency (the normative document supplies no body grammar).
type ProducerHandoff struct {
	Origin, Scope, Event, Sender, Repository, Head string
	PR                                             uint64
	State                                          string // intact
}

type ReviewInventory struct {
	Coverage Coverage
	// SelectedID comes from the authenticated exact-candidate delivery record,
	// not a caller selector. Records include current effective blocking state.
	SelectedID string
	Records    []PlatformReview
}

type PlatformReview struct {
	Repository, ID, Head, Base, Kind, State, Body string
	PR                                            uint64
	SubmittedAt                                   int64
}

// Check identity includes the configured provider application identity, not just
// a same-named context from an unrelated bot. The adapter must normalize the
// actual required-check mechanism without filling unknowns with an empty list.
type CheckIdentity struct{ Name, Application string }
type CheckPolicy struct {
	Repository, Ref, State string // required / no_required / unknown
	Required               []CheckIdentity
}
type CheckRecord struct {
	Identity                            CheckIdentity
	ID, Repository, Head, State, Result string // completed / success
}
type CheckInventory struct {
	Coverage         Coverage
	Repository, Head string
	Records          []CheckRecord
}

// A scope is a configured room at MatrixOrigin. Source must authenticate the
// frontier and its completeness over WindowStart..WindowEnd. Complete is not a
// caller claim. Page replays are deduplicated by exact (scope,event) identity;
// conflicting replays fail. This is per-frontier coverage, not an atomic global
// snapshot or a claim about events arriving after the frontier.
type Lookup struct {
	WindowStart, WindowEnd, ObservedAt int64
	Scopes                             []ScopeRead
}
type ScopeRead struct {
	Origin, Scope, FrontierSHA256 string
	Coverage                      Coverage
	Pages                         int
	Events                        []Event
}
type Event struct {
	ID, Sender, Body, State string // State intact; Body is JSON-decoded UTF-8.
	ServerAt                int64
}

var (
	ErrRejected    = errors.New("authority_rejected")
	ErrUnavailable = errors.New("authority_unavailable")
)

// Refusal exposes a finite predicate with no source text, paths, credentials,
// provider errors or private messaging provenance.
type Refusal struct {
	code      error
	predicate string
}

func (e *Refusal) Error() string {
	if e == nil || e.code == nil {
		return "authority_unavailable"
	}
	return e.code.Error() + ": " + e.predicate
}
func (e *Refusal) Unwrap() error     { return e.code }
func (e *Refusal) Predicate() string { return e.predicate }
func rejected(p string) error        { return &Refusal{ErrRejected, p} }
func unavailable(p string) error     { return &Refusal{ErrUnavailable, p} }

// Summary is the non-private result of this local qualification. It is not an
// opcode33 schema, an admission record, a signature/audit receipt or a perpetual
// release authorization. In particular it contains no Matrix room/event/sender.
type Summary struct {
	Binding                                           Query
	Tree, OwnerFingerprint, DefaultHead, Relationship string
	PR                                                uint64
	PlatformReviewID, Verdict, VerdictBodySHA256      string
	CheckPolicyRef, CheckVerdict                      string
	ObservedAt, ExpiresAt                             int64
}

// Qualification has immutable private state; the zero value is absent. It can
// only be produced by a complete boundary refresh through the configured Source.
type Qualification struct {
	summary         Summary
	clock           Clock
	start           Reading
	deadline        time.Duration
	installed       PolicySource
	installedDigest string
}

func (q *Qualification) Summary() (Summary, bool) {
	if q == nil || q.clock == nil {
		return Summary{}, false
	}
	return q.summary, true
}

// CheckFreshness checks the local lease and, for protected qualifications, the
// current installed digest. It never refreshes provider evidence or establishes
// another phase. BeforeSign must perform its OWN fresh Source read.
// Monotonic capping prevents backward wall movement from extending the lease.
func (q *Qualification) CheckFreshness() error {
	return q.CheckFreshnessContext(context.Background())
}

// CheckFreshnessContext additionally rereads installed policy for protected
// qualifications. Effects must supply the original job context. This does not
// renew the qualification or replace BeforeSign's independent source read.
func (q *Qualification) CheckFreshnessContext(ctx context.Context) error {
	if q == nil || q.clock == nil {
		return unavailable("absent_qualification")
	}
	if ctx == nil {
		return unavailable("authority_budget")
	}
	// Preserve the in-memory route's original point-reading semantics. A
	// simulated one-nanosecond lease is not a real filesystem timeout budget.
	if q.installed == nil {
		if ctx.Err() != nil {
			return unavailable("authority_budget")
		}
		_, err := q.leaseReading()
		if ctx.Err() != nil {
			return unavailable("authority_budget")
		}
		return err
	}
	leading, err := q.leaseReading()
	if err != nil {
		return err
	}
	remaining := q.deadline - leading.end()
	if remaining > AuthorityBudget {
		remaining = AuthorityBudget
	}
	ctx, cancel := context.WithTimeout(ctx, remaining)
	defer cancel()
	if err := checkInstalled(ctx, q.installed, q.installedDigest); err != nil {
		return err
	}
	if ctx.Err() != nil {
		return unavailable("authority_budget")
	}
	final, err := q.leaseReading()
	if ctx.Err() != nil {
		return unavailable("authority_budget")
	}
	if err != nil {
		return err
	}
	if final.Monotonic < leading.end() || final.Wall.Before(leading.Wall) {
		return unavailable("lease_clock")
	}
	return nil
}

func (q *Qualification) leaseReading() (Reading, error) {
	now, err := q.clock.Read()
	if err != nil || !validReading(now) || now.Epoch != q.start.Epoch || now.Monotonic < q.start.end() || now.end() >= q.deadline || now.Wall.Before(q.start.Wall) || now.Wall.Unix() < q.summary.ObservedAt || now.wallEnd().Unix() >= q.summary.ExpiresAt {
		return Reading{}, unavailable("lease_clock")
	}
	return now, nil
}
